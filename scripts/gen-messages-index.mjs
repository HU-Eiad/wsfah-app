// Regenerates messages/<locale>/index.ts from the JSON files in each locale folder,
// and checks that ar and en define exactly the same keys.
// Run: node scripts/gen-messages-index.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.join(process.cwd(), "messages");
const locales = ["ar", "en"];

const flatten = (obj, prefix = "") =>
  Object.entries(obj).flatMap(([k, v]) =>
    v && typeof v === "object" ? flatten(v, `${prefix}${k}.`) : [`${prefix}${k}`]
  );

const keysByLocale = {};
for (const locale of locales) {
  const dir = path.join(root, locale);
  const files = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
  const names = files.map((f) => f.replace(/\.json$/, ""));
  const ident = (n) => "ns_" + n.replace(/[^a-zA-Z0-9]/g, "_");
  const src =
    "// Generated by scripts/gen-messages-index.mjs. Do not edit by hand.\n" +
    names.map((n) => `import ${ident(n)} from "./${n}.json";`).join("\n") +
    "\n\nconst messages = {\n" +
    names.map((n) => `  ${JSON.stringify(n)}: ${ident(n)},`).join("\n") +
    "\n};\n\nexport default messages;\n";
  writeFileSync(path.join(dir, "index.ts"), src);

  keysByLocale[locale] = new Set(
    names.flatMap((n) => flatten(JSON.parse(readFileSync(path.join(dir, `${n}.json`), "utf8")), `${n}.`))
  );
  console.log(`${locale}: ${names.length} namespaces, ${keysByLocale[locale].size} keys`);
}

const [a, b] = locales.map((l) => keysByLocale[l]);
const onlyA = [...a].filter((k) => !b.has(k));
const onlyB = [...b].filter((k) => !a.has(k));
if (onlyA.length || onlyB.length) {
  console.error("Key mismatch!");
  if (onlyA.length) console.error("  only in ar:", onlyA.join(", "));
  if (onlyB.length) console.error("  only in en:", onlyB.join(", "));
  process.exit(1);
}
console.log("ar and en keys match.");
